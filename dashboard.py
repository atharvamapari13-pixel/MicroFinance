
from pathlib import Path

import streamlit as st
import pandas as pd
import plotly.express as px


# ==========================================
# 1. PAGE CONFIGURATION
# ==========================================

PROJECT_DIR = Path(__file__).resolve().parent
RESULTS_DIR = PROJECT_DIR / "results"

CLUSTER_FILE = RESULTS_DIR / "country_clustering_results.csv"
EVALUATION_FILE = RESULTS_DIR / "clustering_evaluation.csv"
GDP_SUMMARY_FILE = RESULTS_DIR / "gdp_country_summary.csv"

st.set_page_config(
    page_title="MicroFinance Analytics",
    page_icon="📊",
    layout="wide"
)


# ==========================================
# 2. CUSTOM STYLING
# ==========================================

st.markdown("""
<style>
    .main-title {
        font-size: 32px;
        font-weight: 700;
        color: #2563EB;
    }

    .subtitle {
        color: #64748B;
        font-size: 15px;
    }

    div[data-testid="stMetric"] {
        background-color: rgba(128, 128, 128, 0.08);
        padding: 16px;
        border-radius: 12px;
        border: 1px solid rgba(128, 128, 128, 0.2);
    }
</style>
""", unsafe_allow_html=True)


# ==========================================
# 3. LOAD DATA
# ==========================================

@st.cache_data
def load_csv(file_path):
    return pd.read_csv(file_path)


def load_optional_file(file_path):
    if file_path.exists():
        try:
            return load_csv(str(file_path))
        except Exception as error:
            st.error(f"Could not read {file_path.name}: {error}")
    return None


st.markdown(
    '<div class="main-title">Microfinance & Economic Growth</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">'
    'Comparative Analysis of Clustering Algorithms Across Countries'
    '</div>',
    unsafe_allow_html=True
)

st.divider()

cluster_df = load_optional_file(CLUSTER_FILE)
evaluation_df = load_optional_file(EVALUATION_FILE)
summary_df = load_optional_file(GDP_SUMMARY_FILE)

if cluster_df is None or evaluation_df is None:
    st.warning(
        "Clustering output files are missing. "
        "Run main.py first to generate the required CSV files."
    )
    st.code("python main.py")
    st.stop()


# ==========================================
# 4. SIDEBAR FILTERS
# ==========================================

st.sidebar.title("Dashboard Controls")

algorithm_columns = {
    "K-Means": "KMeans_Cluster",
    "Agglomerative": "Agglomerative_Cluster",
    "DBSCAN": "DBSCAN_Cluster",
    "Gaussian Mixture Model": "GMM_Cluster"
}

available_algorithms = [
    name for name, column in algorithm_columns.items()
    if column in cluster_df.columns
]

if not available_algorithms:
    st.error(
        "No cluster label columns found. "
        "Check the output generated by main.py."
    )
    st.stop()

selected_algorithm = st.sidebar.selectbox(
    "Select clustering algorithm",
    available_algorithms
)

cluster_column = algorithm_columns[selected_algorithm]

country_names = sorted(
    cluster_df["Country Name"].dropna().astype(str).unique()
)

selected_countries = st.sidebar.multiselect(
    "Filter countries",
    country_names,
    default=[]
)

filtered_df = cluster_df.copy()

if selected_countries:
    filtered_df = filtered_df[
        filtered_df["Country Name"].astype(str).isin(
            selected_countries
        )
    ]


# ==========================================
# 5. KEY PERFORMANCE INDICATORS
# ==========================================

total_countries = cluster_df["Country Code"].nunique()

cluster_labels = cluster_df[cluster_column]
number_of_clusters = cluster_labels[
    cluster_labels != -1
].nunique()

noise_count = (
    int((cluster_labels == -1).sum())
    if selected_algorithm == "DBSCAN"
    else 0
)

algorithm_row = evaluation_df[
    evaluation_df["Algorithm"].str.lower()
    == {
        "K-Means": "kmeans",
        "Agglomerative": "agglomerative",
        "DBSCAN": "dbscan",
        "Gaussian Mixture Model": "gmm"
    }[selected_algorithm]
]

silhouette = (
    algorithm_row["Silhouette_Score"].iloc[0]
    if not algorithm_row.empty else float("nan")
)

runtime = (
    algorithm_row["Runtime_Seconds"].iloc[0]
    if not algorithm_row.empty else float("nan")
)

col1, col2, col3, col4 = st.columns(4)

col1.metric("Countries Analyzed", f"{total_countries:,}")
col2.metric("Clusters Identified", number_of_clusters)
col3.metric(
    "Silhouette Score",
    f"{silhouette:.3f}" if pd.notna(silhouette) else "N/A"
)
col4.metric(
    "Runtime (seconds)",
    f"{runtime:.4f}" if pd.notna(runtime) else "N/A"
)

if selected_algorithm == "DBSCAN":
    st.caption(f"DBSCAN noise points: {noise_count}")


# ==========================================
# 6. DASHBOARD TABS
# ==========================================

tab1, tab2, tab3, tab4 = st.tabs([
    "📈 Overview",
    "🔬 Cluster Analysis",
    "⚖️ Algorithm Comparison",
    "🌍 Country Explorer"
])


# ==========================================
# TAB 1: OVERVIEW
# ==========================================

with tab1:

    st.subheader("Project Overview")

    st.write(
        "This dashboard compares clustering algorithms "
        "and explores similarities between country-level "
        "economic growth profiles."
    )

    if summary_df is not None and "mean" in summary_df.columns:
        overview_col1, overview_col2 = st.columns(2)

        with overview_col1:
            fig = px.histogram(
                summary_df,
                x="mean",
                nbins=30,
                title="Distribution of Mean GDP Growth by Country",
                labels={"mean": "Mean GDP Growth (%)"},
                template="plotly_white"
            )
            st.plotly_chart(fig, use_container_width=True)

        with overview_col2:
            if "std" in summary_df.columns:
                fig = px.histogram(
                    summary_df.dropna(subset=["std"]),
                    x="std",
                    nbins=30,
                    title="GDP Growth Variability Across Countries",
                    labels={"std": "GDP Growth Standard Deviation"},
                    template="plotly_white"
                )
                st.plotly_chart(fig, use_container_width=True)

    st.subheader("Selected Algorithm's Cluster Distribution")

    distribution = (
        cluster_df[cluster_column]
        .value_counts()
        .sort_index()
        .rename_axis("Cluster")
        .reset_index(name="Countries")
    )

    distribution["Cluster"] = distribution["Cluster"].astype(str)

    fig = px.bar(
        distribution,
        x="Cluster",
        y="Countries",
        color="Cluster",
        title=f"{selected_algorithm}: Countries per Cluster",
        template="plotly_white"
    )

    st.plotly_chart(fig, use_container_width=True)


# ==========================================
# TAB 2: CLUSTER ANALYSIS
# ==========================================

with tab2:

    st.subheader(f"{selected_algorithm} Cluster Analysis")

    required_features = [
        "GDP_Mean",
        "GDP_Median",
        "GDP_Std",
        "GDP_Min",
        "GDP_Max",
        "GDP_Years"
    ]

    available_features = [
        feature for feature in required_features
        if feature in filtered_df.columns
    ]

    if len(available_features) >= 2:

        x_feature = st.selectbox(
            "X-axis feature",
            available_features,
            index=0
        )

        y_feature = st.selectbox(
            "Y-axis feature",
            available_features,
            index=min(2, len(available_features) - 1)
        )

        plot_df = filtered_df.dropna(
            subset=[x_feature, y_feature, cluster_column]
        ).copy()

        plot_df["Cluster"] = plot_df[cluster_column].astype(str)

        fig = px.scatter(
            plot_df,
            x=x_feature,
            y=y_feature,
            color="Cluster",
            hover_name="Country Name",
            hover_data=["Country Code"],
            title=f"{selected_algorithm}: Country Clusters",
            template="plotly_white"
        )

        st.plotly_chart(fig, use_container_width=True)

        st.caption(
            "This chart uses original GDP summary features. "
            "It is not a PCA projection."
        )

    else:
        st.info("Required GDP summary features are unavailable.")

    st.subheader("Cluster Statistics")

    if available_features:
        cluster_stats = (
            filtered_df.groupby(cluster_column)[available_features]
            .mean()
            .round(3)
        )

        cluster_stats.index.name = "Cluster"
        st.dataframe(cluster_stats, use_container_width=True)


# ==========================================
# TAB 3: ALGORITHM COMPARISON
# ==========================================

with tab3:

    st.subheader("Compare Clustering Algorithms")

    st.dataframe(
        evaluation_df.round(4),
        use_container_width=True,
        hide_index=True
    )

    metric_options = [
        "Silhouette_Score",
        "Davies_Bouldin_Score",
        "Calinski_Harabasz_Score",
        "Runtime_Seconds"
    ]

    available_metrics = [
        metric for metric in metric_options
        if metric in evaluation_df.columns
    ]

    selected_metric = st.selectbox(
        "Select evaluation metric",
        available_metrics
    )

    fig = px.bar(
        evaluation_df,
        x="Algorithm",
        y=selected_metric,
        color="Algorithm",
        title=f"Algorithm Comparison: {selected_metric}",
        template="plotly_white"
    )

    st.plotly_chart(fig, use_container_width=True)

    st.caption(
        "Higher Silhouette and Calinski–Harabasz scores are "
        "generally preferred; lower Davies–Bouldin scores are "
        "generally preferred. Runtime is dataset-dependent."
    )


# ==========================================
# TAB 4: COUNTRY EXPLORER
# ==========================================

with tab4:

    st.subheader("Explore Countries")

    display_columns = [
        "Country Name",
        "Country Code",
        "GDP_Mean",
        "GDP_Median",
        "GDP_Std",
        "GDP_Min",
        "GDP_Max",
        "GDP_Years",
        cluster_column
    ]

    display_columns = [
        column for column in display_columns
        if column in filtered_df.columns
    ]

    st.dataframe(
        filtered_df[display_columns].sort_values(
            "Country Name"
        ),
        use_container_width=True,
        hide_index=True
    )

    csv_data = filtered_df.to_csv(index=False).encode("utf-8")

    st.download_button(
        label="Download filtered country results",
        data=csv_data,
        file_name="filtered_country_clusters.csv",
        mime="text/csv"
    )


# ==========================================
# 7. FOOTER
# ==========================================

st.divider()

st.caption(
    "MCA Data Mining Project | Microfinance and Economic Growth "
    "| Exploratory country-level GDP clustering"
)
